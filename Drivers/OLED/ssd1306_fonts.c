const SSD1306_Font_t Font_11x18 = {11, 18, Font11x18, NULL};

/* Сопоставление символа -> индекс глифа в компактном массиве Font11x18.
 * Массив содержит только цифры 0–9 (индексы 0–9) и буквы A/B (10/11):
 * этого достаточно для строки вида "250B 20A". Кириллические В и А визуально
 * совпадают с латинскими B и A, поэтому отдельные глифы не нужны. */
static int Font11x18_GlyphIndex(char c) {
    if (c >= '0' && c <= '9') return c - '0';
    if (c == 'A') return 10;
    if (c == 'B') return 11;
    return -1;  // пробел и прочие символы — без глифа (только сдвиг курсора)
}

/* Вывод строки шрифтом 11x18 (цифры, пробел, A, B).
 * Пробел и неизвестные символы сдвигают курсор на ширину символа без отрисовки. */
void ssd1306_WriteString11x18(const char* str, SSD1306_COLOR color) {
    extern SSD1306_t SSD1306;   // определена в ssd1306.c
    const uint8_t w = 11, h = 18;
    while (*str) {
        int gi = Font11x18_GlyphIndex(*str++);
        if (SSD1306_WIDTH  < (SSD1306.CurrentX + w) ||
            SSD1306_HEIGHT < (SSD1306.CurrentY + h)) {
            break;  // не помещается на экране
        }
        if (gi >= 0) {
            for (uint8_t i = 0; i < h; i++) {
                uint16_t b = Font11x18[gi * h + i];
                for (uint8_t j = 0; j < w; j++) {
                    ssd1306_DrawPixel(SSD1306.CurrentX + j, SSD1306.CurrentY + i,
                                      ((b << j) & 0x8000) ? color : (SSD1306_COLOR)!color);
                }
            }
        }
        SSD1306.CurrentX += w;
    }
}
