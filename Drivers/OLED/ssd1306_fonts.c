/**
 * @brief Декодировать один символ UTF-8 и вернуть его код Unicode
 * @param str указатель на указатель строки (продвигается на длину символа)
 * @return код Unicode (0 при ошибке или конце строки)
 */
static uint16_t DecodeUTF8(const char** str) {
    const uint8_t* p = (const uint8_t*)*str;
    uint16_t code = 0;
    if (*p == 0) return 0;
    if (*p < 0x80) {
        code = *p;
        (*str)++;
    } else if ((*p & 0xE0) == 0xC0) {
        // 2-byte sequence
        code = ((*p & 0x1F) << 6) | (*(p+1) & 0x3F);
        (*str) += 2;
    } else if ((*p & 0xF0) == 0xE0) {
        // 3-byte sequence (для BMP хватит, но кириллица в UTF-8 2 байта)
        code = ((*p & 0x0F) << 12) | ((*(p+1) & 0x3F) << 6) | (*(p+2) & 0x3F);
        (*str) += 3;
    } else {
        // Неподдерживаемая длина или ошибка – пропускаем байт
        (*str)++;
        return 0;
    }
    return code;
}

/**
 * @brief Вывод одного символа (UTF-8) шрифтом Font_16x26
 * @param ch_ptr указатель на строку (продвигается после прочитанного символа)
 * @param color цвет
 * @return число байт, использованных из строки (0 при ошибке)
 */
static uint8_t ssd1306_WriteChar16x26_UTF8(const char** ch_ptr, SSD1306_COLOR color) {
    uint16_t code = DecodeUTF8(ch_ptr);
    if (code == 0) return 0;

    // Поиск индекса глифа в таблице
    uint8_t glyph_index = 0; // по умолчанию пробел
    for (const typeof(Font16x26_UnicodeMap[0])* p = Font16x26_UnicodeMap; p->code != 0; p++) {
        if (p->code == code) {
            glyph_index = p->glyph;
            break;
        }
    }

    const SSD1306_Font_t* Font = &Font_16x26;
    const uint8_t char_width = Font->width;  // 16

    // Проверка места на экране
    extern SSD1306_t SSD1306;   // определена в ssd1306.c
    if (SSD1306_WIDTH < (SSD1306.CurrentX + char_width) ||
        SSD1306_HEIGHT < (SSD1306.CurrentY + Font->height)) {
        return 0;
    }

    // Рисование глифа
    for (uint8_t i = 0; i < Font->height; i++) {
        uint16_t b = Font->data[glyph_index * Font->height + i];
        for (uint8_t j = 0; j < char_width; j++) {
            if ((b << j) & 0x8000) {
                ssd1306_DrawPixel(SSD1306.CurrentX + j, SSD1306.CurrentY + i, color);
            } else {
                ssd1306_DrawPixel(SSD1306.CurrentX + j, SSD1306.CurrentY + i, !color);
            }
        }
    }
    SSD1306.CurrentX += char_width;
    return 1;  // успех
}

/**
 * @brief Вывод строки в кодировке UTF-8 шрифтом Font_16x26
 * @param str строка в UTF-8
 * @param color цвет
 */
void ssd1306_WriteStringUTF8(const char* str, SSD1306_COLOR color) {
    while (*str) {
        if (ssd1306_WriteChar16x26_UTF8(&str, color) == 0) {
            break;  // не удалось вывести символ
        }
    }
}

