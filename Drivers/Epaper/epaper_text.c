// Очистка буфера (белый цвет)
void epaper_clear_buffer(uint8_t *buf) {
    memset(buf, 0xFF, ALLSCREEN_BYTES);
}

/*
 * Установка одного пикселя в буфере кадра.
 * x = 0..199 (слева направо)
 * y = 0..199 (сверху вниз)
 * color: 0 = чёрный, 1 = белый
 *
 * Внутреннее представление согласовано с функцией Display_image_new():
 * - колонка buf = 199 - x
 * - номер байта по вертикали = y / 8
 * - бит в байте = 7 - (y % 8)  (старший бит = верхняя строка блока)
 */
void epaper_set_pixel(uint8_t *buf, uint16_t x, uint16_t y, uint8_t color) {
    if (x >= 200 || y >= 200) return;

    uint8_t  col  = 199 - x;               // инверсия горизонтали
    uint8_t  line = y / 8;                 // 0..24
    uint8_t  bit  = 7 - (y % 8);           // 7 = верх, 0 = низ
    uint16_t idx  = (uint16_t)line * 200 + col;

    if (color == 0) {
        buf[idx] &= ~(1 << bit);           // чёрный
    } else {
        buf[idx] |= (1 << bit);            // белый
    }
}

/*
 * Рисование символа шрифтом 8x8 с произвольным масштабированием.
 * scale = 1 -> символ 8x8 пикселей
 * scale = 2 -> 16x16
 * scale = 3 -> 24x24 и т.д.
 */
void epaper_draw_char(uint8_t *buf, uint16_t x, uint16_t y, char ch,
                      const uint8_t (*font)[8], uint8_t scale) {
    if (ch < 32 || ch > 126) ch = 32;
    const uint8_t *glyph = font[ch - 32];

    for (uint8_t row = 0; row < 8; row++) {
        uint8_t line = glyph[row];
        for (uint8_t col = 0; col < 8; col++) {
        	if (line & (1 << col)) {   // пиксель чёрный
                // Рисуем квадрат scale x scale
                for (uint8_t dy = 0; dy < scale; dy++) {
                    for (uint8_t dx = 0; dx < scale; dx++) {
                        epaper_set_pixel(buf, x + col * scale + dx,
                                         y + row * scale + dy, 0);
                    }
                }
            }
        }
    }
}

/*
 * Вывод строки с масштабированием и автоматическим переносом.
 * x, y – координаты левого верхнего угла первого символа.
 * Ширина символа = 8 * scale, высота = 8 * scale.
 */
void epaper_draw_string(uint8_t *buf, uint16_t x, uint16_t y, const char *str,
                        const uint8_t (*font)[8], uint8_t scale) {
    uint16_t cur_x = x;
    uint16_t cur_y = y;
    uint8_t char_width = 8 * scale;
    uint8_t char_height = 8 * scale;

    while (*str) {
        // Перенос строки, если символ не помещается по ширине
        if (cur_y + char_width > 200) {
            cur_y = 0;
            cur_x += char_height;
        }
        // Если вышли за нижнюю границу – прекращаем
        if (cur_x + char_height > 200) break;

        epaper_draw_char(buf, cur_x, cur_y, *str, font, scale);
        cur_y += char_width;
        str++;
    }
}

